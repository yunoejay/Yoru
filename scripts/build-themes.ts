/**
 * Generates `app/themes.generated.css` from the palette registry in
 * `lib/themes.ts`.
 *
 * Run it with `npm run themes:build` (also wired to `predev`/`prebuild`), or
 * `npm run themes:check` to fail when the committed CSS is stale.
 *
 * Why generate instead of hand-writing the CSS: every Tailwind colour package
 * (`white`, `black`, `slate-*`, `brand`, `bg`) now points at a CSS variable, so
 * a theme is just a set of values. Keeping those values in TypeScript means the
 * picker's swatches, the pre-paint bootstrap and the CSS can never disagree.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { DEFAULT_THEME, SLATE_SHADES, THEMES, type Theme } from '../lib/themes';

const OUTPUT = resolve(process.cwd(), 'app/themes.generated.css');

/** Tailwind needs `R G B` (not hex) so opacity modifiers like `/10` keep working. */
function triplet(hex: string): string {
  const raw = hex.trim().replace(/^#/, '');
  const full =
    raw.length === 3
      ? raw
          .split('')
          .map((char) => char + char)
          .join('')
      : raw;

  if (!/^[0-9a-fA-F]{6}$/.test(full)) {
    throw new Error(`Theme palette contains an invalid hex colour: ${hex}`);
  }

  const value = Number.parseInt(full, 16);
  return `${(value >> 16) & 255} ${(value >> 8) & 255} ${value & 255}`;
}

function variables(theme: Theme): string[] {
  const { palette } = theme;
  return [
    ...SLATE_SHADES.map((shade) => `  --slate-${shade}: ${triplet(palette.slate[shade])};`),
    `  --white: ${triplet(palette.white)};`,
    `  --black: ${triplet(palette.black)};`,
    `  --brand: ${triplet(palette.brand)};`,
    `  --brand-accent: ${triplet(palette.brandAccent)};`,
    `  --bg: ${triplet(palette.bg)};`,
    `  --bg-alt: ${triplet(palette.bgAlt)};`,
    `  --shadow-card: ${palette.shadowCard};`,
    `  --glow-primary: ${palette.glowPrimary};`,
    `  --glow-secondary: ${palette.glowSecondary};`,
    `  --scrollbar-track: ${palette.scrollbarTrack};`,
    `  --scrollbar-thumb: ${palette.scrollbarThumb};`,
    `  --scrollbar-thumb-hover: ${palette.scrollbarThumbHover};`,
  ];
}

function render(): string {
  const lines: string[] = [
    '/*',
    ' * AUTO-GENERATED by scripts/build-themes.ts — do not edit by hand.',
    ' * Run `npm run themes:build` after changing lib/themes.ts.',
    ' */',
    '',
    ':root {',
    `  color-scheme: ${DEFAULT_THEME.mode};`,
    ...variables(DEFAULT_THEME),
    '}',
  ];

  for (const theme of THEMES) {
    lines.push('', `[data-theme="${theme.id}"] {`, `  color-scheme: ${theme.mode};`, ...variables(theme), '}');
  }

  return `${lines.join('\n')}\n`;
}

const css = render();
const check = process.argv.includes('--check');

if (check) {
  let current = '';
  try {
    current = readFileSync(OUTPUT, 'utf8');
  } catch {
    console.error('themes: app/themes.generated.css is missing — run `npm run themes:build`.');
    process.exit(1);
  }

  if (current !== css) {
    console.error('themes: app/themes.generated.css is stale — run `npm run themes:build`.');
    process.exit(1);
  }

  console.log(`themes: ${THEMES.length} themes up to date.`);
} else {
  writeFileSync(OUTPUT, css);
  console.log(`themes: wrote ${THEMES.length} themes to app/themes.generated.css`);
}
